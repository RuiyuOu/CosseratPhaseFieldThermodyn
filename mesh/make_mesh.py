#!/usr/bin/env python3
"""Make the solver mesh (mesh.msh) and the grain angles (grain_angles_deg.txt, grain_angles_rad.txt) from the Neper tessellation.

The inputs in this folder were made with Neper (built from github.com/neperfepx/neper), seed 1:
    neper -T -n 8 -dim 2 -id 1 -reg 1 -domain "square(10,10)" -oridescriptor euler-bunge -format tess,geo,ori -o MPTD_2D

usage (from the repository root):
    python3 mesh/make_mesh.py mesh/MPTD_2D.geo mesh/MPTD_2D.ori --out mesh_build
    cd mesh_build && FreeFem++ -nw make_mesh.edp        # writes mesh_build/mesh.msh
then copy mesh_build/mesh.msh and mesh_build/grain_angles_*.txt to the repository root.

Mesh: FreeFem buildmesh with one straight border per .geo line.
  - grain-boundary lines (inside the square): ceil(L/hgb) segments (hgb = 0.05 um), boundary label 100 + line number;
  - lines on the square's sides: ceil(L/hout) segments (hout = 0.1 um), label 1 left (x = 0), 2 bottom (y = 0), 3 right (x = 10), 4 top (y = 10);
  - triangle region = grain number = the .geo Plane Surface number (= row of the .ori file).
Angles: theta = Euler-Bunge phi1 reduced modulo 180 deg into [-180, 0), one row per grain (the in-plane angle with [1-10] out of plane,
  where the lattice repeats every 180 deg).
Check (FreeFem 4.13): mesh.msh has the repository's 29,399 vertices, 58,391 triangles and 1,227 boundary edges, with identical triangles,
grain labels and boundary labels and vertices within 5e-7 um (the .geo stores coordinates to 12 decimals); the angle files are identical.
"""
import argparse, math, os, re
import numpy as np

ap = argparse.ArgumentParser()
ap.add_argument("geo"); ap.add_argument("ori")
ap.add_argument("--hgb", type=float, default=0.05, help="segment length on grain boundaries (um)")
ap.add_argument("--hout", type=float, default=0.1, help="segment length on the outer sides (um)")
ap.add_argument("--size", type=float, default=10.0, help="side of the square domain (um)")
ap.add_argument("--out", default=".", help="folder for make_mesh.edp and the angle files (created)")
a = ap.parse_args()
os.makedirs(a.out, exist_ok=True)

geo = open(a.geo).read()
P = {int(k): (float(x), float(y)) for k, x, y in re.findall(r"Point \((\d+)\) = \{([-\d.eE+]+),([-\d.eE+]+)", geo)}
L = {int(k): (int(p), int(q)) for k, p, q in re.findall(r"Line \((\d+)\) = \{(\d+),(\d+)\}", geo)}
loops = {int(k): [int(v) for v in body.split(",")] for k, body in re.findall(r"Line Loop \((\d+)\) = \{([^}]*)\}", geo)}
surf = {int(k): int(l) for k, l in re.findall(r"Plane Surface \((\d+)\) = \{(\d+)\}", geo)}
S, eps = a.size, 1e-9


def side(p, q):
    """outer label of a line on the square's boundary, else 0"""
    (x0, y0), (x1, y1) = P[p], P[q]
    if abs(x0) < eps and abs(x1) < eps: return 1
    if abs(y0) < eps and abs(y1) < eps: return 2
    if abs(x0 - S) < eps and abs(x1 - S) < eps: return 3
    if abs(y0 - S) < eps and abs(y1 - S) < eps: return 4
    return 0


def inside_point(loop):
    """a point inside the grain polygon: area centroid of its vertex polygon (the grains are convex cells)"""
    pts = []
    for s in loop:
        p, q = L[abs(s)]
        pts.append(P[p] if s > 0 else P[q])
    x, y = np.array(pts).T
    cr = x * np.roll(y, -1) - np.roll(x, -1) * y
    A = cr.sum() / 2
    return float((x + np.roll(x, -1)) @ cr / (6 * A)), float((y + np.roll(y, -1)) @ cr / (6 * A))


borders, calls = [], []
for k, (p, q) in sorted(L.items()):
    lab = side(p, q)
    (x0, y0), (x1, y1) = P[p], P[q]
    n = math.ceil(math.hypot(x1 - x0, y1 - y0) / (a.hout if lab else a.hgb))
    borders.append(f"border b{k}(t=0,1){{ x={x0!r}+t*({x1 - x0!r}); y={y0!r}+t*({y1 - y0!r}); label={lab if lab else 100 + k}; }}  // line {k}")
    calls.append(f"b{k}({n})")
grains = sorted(surf)

edp = ["// generated by make_mesh.py from " + os.path.basename(a.geo) + f" (hgb = {a.hgb} um, hout = {a.hout} um)"]
edp += borders
edp.append("mesh Th = buildmesh(" + " + ".join(calls) + ");")
edp.append("// region -> grain number (the .geo Plane Surface number)")
edp.append("int[int] rmap(Th.nt + 1); rmap = -1;")
for g in grains:
    cx, cy = inside_point(loops[surf[g]])
    edp.append(f"rmap[Th({cx!r}, {cy!r}).region] = {g};")
edp.append("for (int i = 0; i < rmap.n; i++) if (rmap[i] < 0) rmap[i] = i;   // regions not listed keep their number (there should be none)")
edp.append("int[int] rr(2 * rmap.n); for (int i = 0; i < rmap.n; i++) { rr[2*i] = i; rr[2*i+1] = rmap[i]; }")
edp.append("Th = change(Th, region = rr);")
edp.append('savemesh(Th, "mesh.msh");   // in the folder FreeFem runs in')
edp.append('cout << "mesh.msh: " << Th.nv << " vertices, " << Th.nt << " triangles, " << Th.nbe << " boundary edges" << endl;')
open(os.path.join(a.out, "make_mesh.edp"), "w").write("\n".join(edp) + "\n")

phi1 = np.atleast_2d(np.loadtxt(a.ori))[:, 0]
th = ((phi1 + 180.0) % 180.0) - 180.0
np.savetxt(os.path.join(a.out, "grain_angles_deg.txt"), th, fmt="%.18e")
np.savetxt(os.path.join(a.out, "grain_angles_rad.txt"), np.deg2rad(th), fmt="%.18e")
print(f"wrote {a.out}/make_mesh.edp ({len(borders)} borders, {len(grains)} grains), grain_angles_deg.txt, grain_angles_rad.txt")
