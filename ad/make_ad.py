#!/usr/bin/env python3
"""Generate cosserat_kwc_ad.edp from the serial cosserat_kwc.edp: the element-map derivatives of the consistent tangent and of the local
slip/spin Newton (fdMap: central differences, -fdk/-fdq) are replaced by exact forward-mode AD (plugin kwc2d.cpp).  Everything else is the
stable solver unchanged.  -adcheck 1: compare AD and central differences at a perturbed state and stop.
Usage:  python3 ad/make_ad.py cosserat_kwc.edp cosserat_kwc_ad.edp       (each patch must apply exactly once)"""
import sys
src, dst = sys.argv[1], sys.argv[2]
s = open(src).read()
def rep(old, new, count=1):
    global s
    n = s.count(old)
    if n != count: raise SystemExit("patch expected %d match(es), found %d:\n%s" % (count, n, old[:200]))
    s = s.replace(old, new)
rep('load "IncompleteCholesky"   // iLU / iluSolve for the GMRES preconditioner\n',
    'load "IncompleteCholesky"   // iLU / iluSolve for the GMRES preconditioner\n'
    'load "kwc2d"                // exact (AD) element-map derivatives (generated by make_ad.py from cosserat_kwc.edp)\n')
rep('A11c = s3x .* s3y; A11c *= -1; A12c = s3x .* s3x; A21c = s3y .* s3y; A21c *= -1; A22c = s3x .* s3y;\n',
    'A11c = s3x .* s3y; A11c *= -1; A12c = s3x .* s3x; A21c = s3y .* s3y; A21c *= -1; A22c = s3x .* s3y;\n'
    '{ real[int,int] KC(nt, 21);   // per-element constants of the AD element map\n'
    '  KC(:, 0) = C11; KC(:, 1) = C22; KC(:, 2) = C12; KC(:, 3) = C16; KC(:, 4) = C26; KC(:, 5) = C66; KC(:, 6) = B11; KC(:, 7) = B22; KC(:, 8) = B12;\n'
    '  KC(:, 9) = A11a; KC(:, 10) = A12a; KC(:, 11) = A21a; KC(:, 12) = A22a; KC(:, 13) = A11b; KC(:, 14) = A12b; KC(:, 15) = A21b; KC(:, 16) = A22b;\n'
    '  KC(:, 17) = A11c; KC(:, 18) = A12c; KC(:, 19) = A21c; KC(:, 20) = A22c;\n'
    '  real[int] kp = [muc, K0eos, Kpeos, Clxx]; k2dSetup(KC, kp); k2dThreads(atoi(arg("-threads", "1"))); }\n')
rep('// central differences of the element map w.r.t. inputs j0..j1 (fills DSF, DTQ); restores the base state\nfunc int fdMap(int j0, int j1) {',
    '// exact derivatives of the element map w.r.t. all 9 inputs by forward-mode AD (fills DSF, DTQ); then the base state as fdMap leaves it\n'
    'real[int,int] ADin(nt, 13);\n'
    'func int fdMap(int j0, int j1) {\n'
    '  ADin(:, 0) = e11; ADin(:, 1) = hy1; ADin(:, 2) = hx2; ADin(:, 3) = e22; ADin(:, 4) = thc; ADin(:, 5) = dpa; ADin(:, 6) = dpb; ADin(:, 7) = dpc; ADin(:, 8) = dwst;\n'
    '  ADin(:, 9) = fp11; ADin(:, 10) = fp12; ADin(:, 11) = fp21; ADin(:, 12) = fp22;\n'
    '  k2dJac(ADin, DSF, DTQ);\n'
    '  taus();\n'
    '  return 0;\n'
    '}\n'
    '// central differences of the element map w.r.t. inputs j0..j1 (the stable solver\'s fdMap; -adcheck only)\nfunc int fdMapFD(int j0, int j1) {')
rep('strength();\nlocalUpdate();\nrefreshTangent();\n\nint nsteps',
    'strength();\nlocalUpdate();\n'
    'if (atoi(arg("-adcheck", "0"))) {   // AD vs central differences of the element map at a perturbed state (all elements)\n'
    '  randinit(5);\n'
    '  for (int k = 0; k < nt; k++) { e11[k] += 0.01*(2*randreal1() - 1); hy1[k] += 0.01*(2*randreal1() - 1); hx2[k] += 0.01*(2*randreal1() - 1); e22[k] += 0.01*(2*randreal1() - 1);\n'
    '    thc[k] += 0.05*(2*randreal1() - 1); dpa[k] = 1e-3*(2*randreal1() - 1); dpb[k] = 1e-3*(2*randreal1() - 1); dpc[k] = 1e-3*(2*randreal1() - 1); dwst[k] = 1e-3*(2*randreal1() - 1); }\n'
    '  real[int] s0 = e11, s1 = hy1, s2 = hx2, s3 = e22, s4 = thc;\n'
    '  real[int,int] FS(nt, 45), FT(nt, 36); real tf0 = clock(); fdMapFD(0, 8); real tfd = clock() - tf0; FS = DSF; FT = DTQ;\n'
    '  e11 = s0; hy1 = s1; hx2 = s2; e22 = s3; thc = s4;\n'
    '  tf0 = clock(); fdMap(0, 8); real tad = clock() - tf0;\n'
    '  real[int,int] VO(nt, 10); k2dMap(ADin, VO);\n'
    '  real ev = 0; { real[int] o(nt); outI(0, o); real[int] d = VO(:, 0); d -= o; ev = max(ev, d.linfty); outI(4, o); d = VO(:, 4); d -= o; ev = max(ev, d.linfty); outI(5, o); d = VO(:, 5); d -= o; ev = max(ev, d.linfty); outI(8, o); d = VO(:, 8); d -= o; ev = max(ev, d.linfty); }\n'
    '  for (int i = 0; i < 9; i++) { real e = 0, m = 0; for (int j = 0; j < 9; j++) { real[int] a(nt), f(nt);\n'
    '      if (i < 5) { a = DSF(:, i*9 + j); f = FS(:, i*9 + j); } else { a = DTQ(:, (i-5)*9 + j); f = FT(:, (i-5)*9 + j); }\n'
    '      m = max(m, a.linfty); f -= a; e = max(e, f.linfty); }\n'
    '    cout << "adcheck: output " << i << "  max |FD - AD| " << e << "  (max |AD| " << m << ")" << endl; }\n'
    '  cout << "adcheck: values plugin vs solver max |diff| " << ev << ";  time FD " << tfd << " s, AD " << tad << " s (" << nt << " elements)" << endl;\n'
    '  exit(0);\n'
    '}\n'
    'refreshTangent();\n\nint nsteps')
open(dst, "w").write(s)
print("wrote", dst)
